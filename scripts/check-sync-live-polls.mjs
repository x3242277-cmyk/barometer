import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir, mkdtemp } from 'node:fs/promises';
import path from 'node:path';
import { mergeLivePolls, syncLivePolls, validateLiveFeed } from './sync-live-polls.mjs';

const archive = JSON.parse(await readFile('data/polls-archive.json', 'utf8'));
const firms = JSON.parse(await readFile('data/pollsters.json', 'utf8'));
const first = structuredClone(archive.polls[0]);
const fresh = { ...structuredClone(first), id: 'manual-channel_12-2026-10-08', sourceId: 'channel_12', channelHebrewName: 'חדשות 12', date: '08.10.2026', dateTimestamp: Date.parse('2026-10-08'), publishedAt: Date.parse('2026-10-08T09:00:00Z') };
const merged = mergeLivePolls([first], [fresh]);
assert.equal(merged.added, 1);
assert.equal(merged.polls.length, 2);
assert(merged.polls.some(p => p.id === first.id));
assert.equal(mergeLivePolls(merged.polls, [fresh]).added, 0);
const renamed = { ...fresh, id: 'another-import-of-the-same-survey' };
assert.equal(mergeLivePolls(merged.polls, [renamed]).polls.length, 2);
const corrected = structuredClone(fresh);
corrected.parties = [{ ...fresh.parties[0], mandates: 120 }];
corrected.publishedAt++;
assert.equal(mergeLivePolls([fresh], [corrected]).changed, 1);
assert.equal(mergeLivePolls([corrected], [fresh]).changed, 0, 'an older deployment rolled a correction back');
assert.throws(() => validateLiveFeed({ polls: [fresh, renamed] }, firms.sourceMap));
assert.throws(() => validateLiveFeed({ polls: [{ ...fresh, dateTimestamp: 0 }] }, firms.sourceMap));
assert.throws(() => validateLiveFeed({ polls: [{ ...fresh, parties: [{ id: 'likud', mandates: 119 }] }] }, firms.sourceMap));

await mkdir('.site-stage', { recursive: true });
const root = await mkdtemp(path.resolve('.site-stage/sync-polls-test-'));
await mkdir(path.join(root, 'data')); await mkdir(path.join(root, 'scripts'));
const save = (name, data) => writeFile(path.join(root, name), JSON.stringify(data));
await save('scripts/config.json', { year: 2026, maxPerOutlet: 4, from: '2026-08-01', liveSiteUrl: 'https://test.example' });
await save('data/pollsters.json', firms);
await save('data/current-polls.json', { generatedAt: '2026-10-07T00:00:00Z', selection: {}, polls: [first] });
await save('data/polls-archive.json', { polls: [first] });
const fetcher = async () => Response.json({ updatedAt: '2026-10-08T09:00:00Z', polls: [fresh] });
const result = await syncLivePolls({ root, fetcher });
assert.equal(result.added, 1);
const saved = JSON.parse(await readFile(path.join(root, 'data/polls-archive.json'), 'utf8'));
assert.equal(saved.polls.length, 2);
assert(saved.polls.some(p => p.id === first.id));
const bytes = await readFile(path.join(root, 'data/polls-archive.json'), 'utf8');
assert.equal((await syncLivePolls({ root, fetcher })).added, 0);
assert.equal(await readFile(path.join(root, 'data/polls-archive.json'), 'utf8'), bytes);
await assert.rejects(syncLivePolls({ root, fetcher: async () => Response.json({ polls: [fresh] }, { headers: { 'X-Barometer-Data-Status': 'fallback' } }) }));
await assert.rejects(syncLivePolls({ root, fetcher: async () => Response.json({ polls: [] }) }));
assert.equal(await readFile(path.join(root, 'data/polls-archive.json'), 'utf8'), bytes);
console.log('Passed: live polls retained with repository history, repeat sync without changes, publisher/date deduplication, newer correction, older-deploy protection, validation, backup before writing and failure without data loss.');
