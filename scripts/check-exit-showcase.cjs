const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const ctx=vm.createContext({console,Date,Intl,Math});
vm.runInContext(fs.readFileSync('assets/app.js','utf8'),ctx);
const channels=vm.runInContext('EXIT_SHOWCASE_CHANNELS',ctx);
assert.deepEqual([...channels.map(c=>c.id)],['kan_news','channel_12','channel_13','channel_14','i24news']);
assert(channels.every(c=>!c.year));
assert.equal(vm.runInContext('EXIT_SLIDE_MS',ctx),9000);
const waiting=vm.runInContext('exitSlideHTML(EXIT_SHOWCASE_CHANNELS[4],"current",{})',ctx);
assert(waiting.includes('מחכים למדגם 2026'));
const data={samples:{channel_12:{sourceId:'channel_12',parties:[{id:'likud',mandates:120}]}}};
ctx.fixture=data;
assert.equal(vm.runInContext('exitSample(fixture,EXIT_SHOWCASE_CHANNELS[1]).parties[0].mandates',ctx),120);
assert.equal(vm.runInContext('exitSample(fixture,EXIT_SHOWCASE_CHANNELS[0])',ctx),null);
const NativeDate=Date;
ctx.Date=class extends NativeDate{static now(){return NativeDate.parse('2026-10-27T22:00:01+02:00')}};
const published=vm.runInContext('exitSlideHTML(EXIT_SHOWCASE_CHANNELS[1],"current",fixture)',ctx);
assert(published.includes('נתוני הגושים')&&published.includes('120')&&!published.includes('מחכים למדגם'));
for(const channel of channels){assert(fs.existsSync(channel.logo),channel.logo);if(channel.photo)assert(fs.existsSync(channel.photo),channel.photo);}
const channel13=vm.runInContext('exitSlideHTML(EXIT_SHOWCASE_CHANNELS[2],"photo",{})',ctx);
assert(channel13.includes('assets/exit-2022-channel13.png')&&!channel13.includes('שחזור'));
const cardsSource=fs.readFileSync('assets/app.js','utf8');
assert(cardsSource.includes('<span class="es-slide-logo"><img')&&!cardsSource.includes('class="es-channel-logo"')&&!cardsSource.includes('class="es-channel-mark"'));
assert(cardsSource.includes('const kinds=["current","photo"]')&&!cardsSource.includes('kind==="historical"'));
assert(!cardsSource.includes('class="es-progress"')&&!cardsSource.includes('class="es-dots"'));
const css=fs.readFileSync('assets/exit-showcase.css','utf8'),sceneCss=fs.readFileSync('assets/election.css','utf8'),html=fs.readFileSync('index.html','utf8');
assert(css.includes('grid-template-columns:repeat(5,minmax(0,1fr))')&&css.includes('var(--knesset-scene)'));
assert(sceneCss.includes("--knesset-scene:url('election-knesset.png')")&&css.includes('.exit-scene-image'));
assert(css.includes('transition:opacity .85s ease')&&css.includes('body:has(#view-live.on){overflow:hidden}'));
assert(html.indexOf('data-night-countdown')<html.indexOf('id="exit-showcase-grid"')&&html.includes('לא יתקיים שידור חי באתר'));
console.log('Passed: five publisher cards, two smoothly rotating screens per channel, authentic 2022 images, top countdown, one-screen Knesset background, and channel-specific 2026 lookup.');
